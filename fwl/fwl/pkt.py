def _ipv4_str_to_int(addr: str, where: str) -> int:
  """Dotted-quad to host-order u32 (high octet first), with validation."""
  if not isinstance(addr, str):
    raise ValueError(f"{where}: expected dotted-quad string, got {addr!r}")
  parts = addr.split(".")
  if len(parts) != 4:
    raise ValueError(f"{where}: not an IPv4 dotted quad: {addr!r}")
  value = 0
  for part in parts:
    n = int(part)
    if not (0 <= n <= 255):
      raise ValueError(f"{where}: IPv4 octet out of range 0..255: {n}")
    value = (value << 8) | n
  return value


def _parse_nat_state(raw: Any) -> tuple:
  """Parse `state.nat` into `(masq_ip_int_or_None, mappings_tuple)`.

  `masq_ip` is the masquerade source IPv4. `mappings` is a list of
  reply-direction entries used to de-NAT return traffic; each carries
  the forward 5-tuple the return packet presents (proto/src_ip/dst_ip/
  src_port/dst_port), the address+port to restore (new_ip/new_port), and
  the direction `nat_type` ('snat' rewrites source, 'dnat' rewrites
  destination). Returned mappings are
  `(proto, src_u32, dst_u32, sport, dport, new_u32, new_port, kind)`.
  """
  if raw is None:
    return (None, ())
  if not isinstance(raw, dict):
    raise ValueError("state.nat must be a mapping")
  _reject_unknown_keys(raw, _NAT_STATE_KEYS, "state.nat")
  masq = raw.get("masq_ip")
  masq_ip = (_ipv4_str_to_int(masq, "state.nat.masq_ip")
             if masq is not None else None)
  out: list[tuple] = []
  for i, m in enumerate(raw.get("mappings") or []):
    if not isinstance(m, dict):
      raise ValueError(f"state.nat.mappings[{i}] must be a mapping")
    _reject_unknown_keys(m, _NAT_MAPPING_KEYS, f"state.nat.mappings[{i}]")
    proto = m.get("proto")
    if proto not in _CONNTRACK_PROTO_NUM:
      raise ValueError(
        f"state.nat.mappings[{i}].proto must be tcp/udp/icmp"
      )
    kind = m.get("nat_type")
    if kind not in ("snat", "dnat"):
      raise ValueError(
        f"state.nat.mappings[{i}].nat_type must be snat or dnat"
      )
    w = f"state.nat.mappings[{i}]"
    out.append((
      proto,
      _ipv4_str_to_int(m["src_ip"], f"{w}.src_ip"),
      _ipv4_str_to_int(m["dst_ip"], f"{w}.dst_ip"),
      int(m.get("src_port", 0)),
      int(m.get("dst_port", 0)),
      _ipv4_str_to_int(m["new_ip"], f"{w}.new_ip"),
      int(m.get("new_port", 0)),
      kind,
    ))
  return (masq_ip, tuple(out))


def _parse_conntrack_seed(raw: Any) -> tuple:
  """Parse `state.conntrack` into normalized forward 5-tuple keys.

  Each entry is a mapping with src_ip/dst_ip/proto (required) and
  optional src_port/dst_port (default 0, as for ICMP). v0.4 conntrack
  is IPv4-only, so v6 addresses are rejected. The returned keys match
  the interpreter's `ConntrackTable` format:
  `(proto_str, src_u32, dst_u32, src_port, dst_port)`.
  """
  if raw is None:
    return ()
  if not isinstance(raw, list):
    raise ValueError("state.conntrack must be a list of entries")
  out: list[tuple] = []
  for i, entry in enumerate(raw):
    if not isinstance(entry, dict):
      raise ValueError(f"state.conntrack[{i}] must be a mapping")
    _reject_unknown_keys(
      entry, _CONNTRACK_ENTRY_KEYS, f"state.conntrack[{i}]"
    )
    proto = entry.get("proto")
    if proto not in _CONNTRACK_PROTO_NUM:
      raise ValueError(
        f"state.conntrack[{i}].proto must be one of "
        f"tcp/udp/icmp (v0.4 conntrack is IPv4-only); got {proto!r}"
      )
    if "src_ip" not in entry or "dst_ip" not in entry:
      raise ValueError(
        f"state.conntrack[{i}] requires src_ip and dst_ip"
      )
    src = _ipv4_str_to_int(entry["src_ip"], f"state.conntrack[{i}].src_ip")
    dst = _ipv4_str_to_int(entry["dst_ip"], f"state.conntrack[{i}].dst_ip")
    sport = int(entry.get("src_port", 0))
    dport = int(entry.get("dst_port", 0))
    out.append((proto, src, dst, sport, dport))
  return tuple(out)


def _reject_unknown_keys(
  block: dict, allowed: frozenset[str], where: str,
) -> None:
  """Per PKT_V01_SPEC.md:39, unknown keys at any documented level
  are validation errors — silently discarding typos breaks tests."""
  for key in block:
    if key not in allowed:
      raise ValueError(f"unknown field {key!r} at {where}")


def _build_from_spec(builder_text: str, truncate_to: Any) -> Packet:
  """Build a Packet from a builder string + optional truncate_to.

  truncate_to (optional) truncates the built packet to N bytes and
  strips the decoded fields that would land past it, mirroring the
  BPF parser's bounds checks so the two oracles agree on partial
  frames (PKT_V01_SPEC.md "test_packet").
  """
  fields = parse_builder(builder_text)
  packet = build_packet(fields)
  if truncate_to is not None:
    if not isinstance(truncate_to, int) or truncate_to < 0:
      raise ValueError("truncate_to must be ≥ 0")
    if truncate_to < len(packet.raw):
      packet = Packet(
        raw=packet.raw[:truncate_to],
        fields=_strip_truncated_fields(packet.fields, truncate_to),
      )
  return packet


def _parse_rate_limit_state(doc: dict) -> dict[int, dict[Any, int]]:
  """Parse + validate the `state.rate_limit` block.

  Per PKT_V01_SPEC.md:256, every key must reference a rule index that
  exists AND carries a rate_limit modifier; bucket counts must be
  non-negative integers.
  """
  raw_state = (doc.get("state") or {}).get("rate_limit", {})
  state: dict[int, dict[Any, int]] = {}
  if not raw_state:
    return state
  valid = _rate_limit_rule_indices(doc["source_fw"])
  for rule_idx, buckets in raw_state.items():
    idx = int(rule_idx)
    if idx not in valid:
      raise ValueError(
        f"state.rate_limit references rule index {idx} without a "
        f"rate_limit modifier"
      )
    for bucket_key, count in buckets.items():
      if not isinstance(count, int) or isinstance(count, bool):
        raise ValueError(
          f"state.rate_limit[{idx}][{bucket_key!r}] must be a "
          f"non-negative integer; got {count!r}"
        )
      if count < 0:
        raise ValueError(
          f"state.rate_limit[{idx}][{bucket_key!r}] must be a "
          f"non-negative integer; got {count}"
        )
    state[idx] = dict(buckets)
  return state


def _parse_geoip_data(doc: dict) -> dict[str, list[str]]:
  """Parse + validate the `geoip_data` block (v0.2)."""
  raw_geoip = doc.get("geoip_data") or {}
  geoip_data: dict[str, list[str]] = {}
  for code, prefixes in raw_geoip.items():
    if not isinstance(code, str) or len(code) != 2 or not code.isupper():
      raise ValueError(
        f"geoip_data key {code!r} must be an uppercase 2-letter "
        f"ISO 3166-1 alpha-2 country code"
      )
    if not isinstance(prefixes, list):
      raise ValueError(
        f"geoip_data[{code}] must be a list of CIDR strings"
      )
    geoip_data[code] = [str(p) for p in prefixes]
  return geoip_data


def _check_counter_changes_declared(doc: dict, expected: dict) -> None:
  """Reject counter_changes naming a counter the source doesn't declare."""
  counter_changes = expected.get("counter_changes", {})
  if counter_changes:
    declared = _declared_counter_names(doc["source_fw"])
    for name in counter_changes:
      if name not in declared:
        raise ValueError(f"counter '{name}' not declared in source_fw")


def _load_sequence(doc: dict, path: Path) -> PktCase:
  """Load a multi-packet `sequence:` case (v0.4 conntrack)."""
  raw_steps = doc["sequence"]
  if not isinstance(raw_steps, list) or not raw_steps:
    raise ValueError("sequence must be a non-empty list of steps")
  steps: list[PktStep] = []
  for i, raw in enumerate(raw_steps):
    _reject_unknown_keys(raw, _SEQUENCE_STEP_KEYS, f"sequence[{i}]")
    if "builder" not in raw or "expected" not in raw:
      raise ValueError(f"sequence[{i}] requires builder and expected")
    _reject_unknown_keys(
      raw["expected"], _EXPECTED_KEYS, f"sequence[{i}].expected"
    )
    _check_counter_changes_declared(doc, raw["expected"])
    packet = _build_from_spec(raw["builder"], raw.get("truncate_to"))
    steps.append(PktStep(
      name=raw.get("name", f"step {i}"),
      packet=packet,
      expected=raw["expected"],
    ))
  _seq_nat = _parse_nat_state((doc.get("state") or {}).get("nat"))
  return PktCase(
    name=doc["name"],
    source_fw=doc["source_fw"],
    # The first step doubles as the case's `packet`/`expected` so code
    # that peeks at those attributes stays valid; the runner drives the
    # full `sequence` list.
    packet=steps[0].packet,
    expected=steps[0].expected,
    state=_parse_rate_limit_state(doc),
    path=path,
    geoip_data=_parse_geoip_data(doc),
    conntrack_seed=_parse_conntrack_seed(
      (doc.get("state") or {}).get("conntrack")
    ),
    # `state.nat` was parsed for single-packet cases and silently
    # dropped for sequences, so a sequence could declare a masquerade
    # address or a reply mapping and have both oracles ignore it — the
    # assertion looked present and did nothing.
    nat_masq_ip=_seq_nat[0],
    nat_mappings=_seq_nat[1],
    sequence=tuple(steps),
    ingress_zone=doc.get("ingress_zone"),
  )


def load(path: Path) -> PktCase:
  """Load a `.pkt` YAML file from disk.

  Two shapes: a single `test_packet`/`expected` pair (v0.1+), or a
  v0.4 `sequence:` of ordered packets sharing one conntrack table.
  Both may carry a `state.conntrack` pre-seed block.
  """
  text = path.read_text(encoding="utf-8")
  doc = yaml.safe_load(text)
  _reject_unknown_keys(doc, _TOP_LEVEL_KEYS, "top level")
  if doc.get("state") is not None:
    _reject_unknown_keys(doc["state"], _STATE_KEYS, "state")

  if doc.get("sequence") is not None:
    if "test_packet" in doc or "expected" in doc:
      raise ValueError(
        "a sequence case must not also define test_packet/expected"
      )
    return _load_sequence(doc, path)

  _reject_unknown_keys(
    doc["test_packet"], _TEST_PACKET_KEYS, "test_packet"
  )
  _reject_unknown_keys(doc["expected"], _EXPECTED_KEYS, "expected")

  packet = _build_from_spec(
    doc["test_packet"]["builder"], doc["test_packet"].get("truncate_to")
  )
  state = _parse_rate_limit_state(doc)
  _check_counter_changes_declared(doc, doc["expected"])
  geoip_data = _parse_geoip_data(doc)
  conntrack_seed = _parse_conntrack_seed(
    (doc.get("state") or {}).get("conntrack")
  )
  nat_masq_ip, nat_mappings = _parse_nat_state(
    (doc.get("state") or {}).get("nat")
  )
  if "output_packet" in doc["expected"]:
    _reject_unknown_keys(
      doc["expected"]["output_packet"], _OUTPUT_PACKET_KEYS,
      "expected.output_packet",
    )

  return PktCase(
    name=doc["name"],
    source_fw=doc["source_fw"],
    packet=packet,
    expected=doc["expected"],
    state=state,
    path=path,
    geoip_data=geoip_data,
    conntrack_seed=conntrack_seed,
    ingress_zone=doc.get("ingress_zone"),
    nat_masq_ip=nat_masq_ip,
    nat_mappings=nat_mappings,
  )


def _strip_truncated_fields(
  fields: dict[str, Any], truncate_to: int
) -> dict[str, Any]:
  """Mirror the BPF parser's bounds-check on a truncated frame.

  Per the v0.2 emitter prelude: the parser bumps `v4_ok`/`v6_ok`
  only when the L3 header fits, and `l4_ok` only when the L4
  header fits. The decoded-field dict the interpreter consumes
  must reflect those gates by dropping fields the parser couldn't
  read on this truncated frame.

  Layout offsets (Ethernet II). A present 802.1Q tag shifts every
  L3/L4 offset by 4 (`l2_end` is 18 instead of 14):
    14 / 18       end of Ethernet header (untagged / tagged)
    +20           end of IPv4 fixed header (ihl=5)
    +40           end of IPv6 fixed header
    +20           full TCP header (ports + flag byte) readable

  VLAN-tag layout: TPID at 12, TCI at 14, inner EtherType at 16, so
  the vlan fields are readable once the 4-byte tag fits
  (truncate_to >= 16) and L3 begins at offset 18.

  Beyond v0.1's IHL≠5 case, the spec deferred extension headers,
  variable-IHL, and L4-after-IPv6-extensions, so this helper assumes
  the builder defaults (IHL=5, no v6 ext headers, single VLAN tag).
  """
  out = dict(fields)
  ether_type = out.get("ether_type")
  is_v6 = ether_type == 0x86DD
  # A present 802.1Q tag shifts every L3/L4 offset by 4 (l2_end is 18
  # instead of 14), so all boundaries below derive from l2_end.
  has_vlan = "vlan_id" in out or "vlan_priority" in out
  l2_end = 18 if has_vlan else 14
  l3_end = l2_end + (40 if is_v6 else 20)
  # L4 port/TCP-flag fields (gated by l4_ok) and ICMP type/code fields
  # (gated by icmp_ok/icmp6_ok) parse at different header sizes, so
  # they get separate truncation boundaries below.
  l4_keys = (
    "src_port", "dst_port",
    "syn", "ack", "fin", "rst", "psh", "urg", "ece", "cwr",
  )
  icmp_keys = ("icmp_type", "icmp_code", "icmp6_type", "icmp6_code")
  # VLAN fields are readable only once the full 4-byte tag fits
  # (bytes 12..16). A frame truncated inside the tag leaves them
  # unreadable, mirroring the emitter's vlan_ok gate.
  if has_vlan and truncate_to < 16:
    out.pop("vlan_id", None)
    out.pop("vlan_priority", None)
  if truncate_to < l2_end:
    out.pop("ether_type", None)
  if truncate_to < l3_end:
    for key in (
      "proto", "src_ip", "dst_ip", "src_ip6", "dst_ip6",
    ):
      out.pop(key, None)
    for key in l4_keys + icmp_keys:
      out.pop(key, None)
    return out
  # The BPF emitter's L4 parse only sets `l4_ok` after a *full*
  # tcphdr/udphdr fits — not just the port pair. tcphdr is 20 B,
  # udphdr is 8 B. Use the conservative tcphdr-sized gate for both
  # so the interpreter mirrors BPF on every truncation boundary.
  if truncate_to < l3_end + 20:
    for key in l4_keys:
      out.pop(key, None)
  # The emitter reads ICMP/ICMPv6 type+code via a minimal 2-byte
  # struct fwl_icmphdr, setting icmp_ok/icmp6_ok only when those 2
  # bytes fit. Mirror that exact boundary.
  if truncate_to < l3_end + 2:
    for key in icmp_keys:
      out.pop(key, None)
  return out


def _rate_limit_rule_indices(source_fw: str) -> frozenset[int]:
  """Indices of rules in `source_fw` that carry a rate_limit modifier.

  Imported lazily to avoid an import cycle if the parser module ever
  grows a dependency on this one.
  """
  from . import analyzer, ast, parser
  program = analyzer.analyze(parser.parse(source_fw))
  return frozenset(
    idx for idx, rule in enumerate(program.rules)
    if isinstance(rule.modifier, ast.RateLimit)
  )


def _declared_counter_names(source_fw: str) -> frozenset[str]:
  """Counter names declared by `count <name>` rules in `source_fw`."""
  from . import analyzer, ast, parser
  program = analyzer.analyze(parser.parse(source_fw))
  return frozenset(
    rule.counter_name
    for rule in program.rules
    if rule.action == ast.Action.COUNT and rule.counter_name
  )
