"""`.pkt` test format loader and packet builder mini-language.

A `.pkt` file is a YAML document. The `test_packet.builder` field is a
small expression language — NOT eval'd Python — describing how to
build the test packet. Builder syntax:

    tcp(src_ip="1.2.3.4", dst_port=22, syn=true, ack=false)
    udp(dst_ip="8.8.8.8", dst_port=53)
    icmp(src_ip="1.1.1.1")

The builder produces raw Ethernet+IPv4+L4 bytes for BPF_PROG_RUN
together with a decoded-fields dict the AST interpreter consumes.

Why a parsed mini-language and not eval'd Python: corpus content is
generated by AI agents and reviewed by humans. eval()ing
agent-generated code would be a security and correctness footgun for
zero gain — the mini-language is ~80 lines of straightforward parsing.
"""
from __future__ import annotations
import re
import struct
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml


@dataclass(frozen=True)
class Packet:
  """A test packet: raw Ethernet frame + decoded fields.

  `raw` is what BPF_PROG_RUN sees. `fields` is what the AST
  interpreter consumes. Both are derived from the same builder call
  so the two oracles see consistent inputs.
  """
  raw: bytes
  fields: dict[str, Any]


@dataclass(frozen=True)
class PktCase:
  """A loaded `.pkt` test case.

  `state` carries pre-existing rate-limit bucket counts keyed by
  rule index. Format in the .pkt file:

    state:
      rate_limit:
        0: { "1.2.3.4": 5 }    # rule index 0, bucket "1.2.3.4" = 5

  Empty dict when the file omits a `state:` block.

  `geoip_data` carries a country-code → CIDR-list mapping (v0.2)
  used by geoip(...) lookups. Mirrors the bundle's `geoip.json`.
  Format in the .pkt file:

    geoip_data:
      RU: ["5.8.0.0/16", "2a00:1370::/32"]
      CN: ["1.0.1.0/24"]

  Empty dict when the file omits a `geoip_data:` block — geoip
  lookups against an empty dict always miss.
  """
  name: str
  source_fw: str
  packet: Packet
  expected: dict[str, Any]
  state: dict[int, dict[Any, int]]
  path: Path
  geoip_data: dict[str, list[str]] = None  # type: ignore[assignment]
  # v0.4 conntrack. `conntrack_seed` holds pre-existing forward
  # 5-tuple keys (proto str, src u32, dst u32, sport, dport) from the
  # `state.conntrack` block — both oracles start with these entries
  # present. `sequence`, when set, makes this a multi-packet case: an
  # ordered list of PktStep run against one carried-over conntrack
  # table (interpreter) / one loaded BPF object (bpf).
  conntrack_seed: tuple = ()
  sequence: tuple = None  # type: ignore[assignment]
  # v0.4 § 6: the zone the packet arrives on, naming which @xdp block
  # evaluates it in a multi-zone unit. None selects the first/only
  # block (the degenerate single-zone case).
  ingress_zone: str = None  # type: ignore[assignment]
  # Phase 5 NAT. `nat_masq_ip` is the masquerade source (the WAN IP the
  # `state.nat.masq_ip` block supplies, a 32-bit int) and `nat_mappings`
  # the pre-seeded reply mappings for return-traffic de-NAT: each a tuple
  # `(proto_str, src_u32, dst_u32, src_port, dst_port, new_u32,
  # new_port, kind)` where kind is 'snat' or 'dnat'.
  nat_masq_ip: int = None  # type: ignore[assignment]
  nat_mappings: tuple = ()


@dataclass(frozen=True)
class PktStep:
  """One ordered packet in a multi-packet `sequence:` case (v0.4)."""
  name: str
  packet: Packet
  expected: dict[str, Any]


_BUILDER_RE = re.compile(
  r"""
  ^\s*
  (?P<proto>tcp6|udp6|icmp6|tcp|udp|icmp)
  \s*\(\s*
  (?P<args>.*?)
  \s*\)\s*$
  """,
  re.VERBOSE,
)


def _parse_value(text: str) -> Any:
  """Parse one builder argument value: int, bool, or quoted string."""
  text = text.strip()
  if text == "true":
    return True
  if text == "false":
    return False
  if text.startswith('"') and text.endswith('"'):
    return text[1:-1]
  if re.fullmatch(r"-?\d+", text):
    return int(text)
  if re.fullmatch(r"0x[0-9a-fA-F]+", text):
    return int(text, 16)
  raise ValueError(f"unrecognized builder value: {text!r}")


def _split_args(args_text: str) -> list[tuple[str, str]]:
  """Split `a=1, b="x", c=true` honoring quoted strings.

  v0.1 builder values don't include commas inside strings or nested
  parens, so a small state-machine split is enough.
  """
  if not args_text.strip():
    return []
  parts: list[str] = []
  current: list[str] = []
  in_string = False
  for ch in args_text:
    if ch == '"':
      in_string = not in_string
      current.append(ch)
    elif ch == "," and not in_string:
      parts.append("".join(current))
      current = []
    else:
      current.append(ch)
  parts.append("".join(current))

  result: list[tuple[str, str]] = []
  for part in parts:
    if "=" not in part:
      raise ValueError(
        f"builder argument missing '=': {part!r}"
      )
    name, _, value = part.partition("=")
    result.append((name.strip(), value.strip()))
  return result


# v0.4 adds the six remaining TCP flags to the tcp/tcp6 builders and
# type/code to the icmp/icmp6 builders (f-04a), plus the VLAN tag
# fields to every builder (f-04b).
_TCP_BUILDER_FIELDS = frozenset({
  "src_ip", "dst_ip", "src_port", "dst_port",
  "syn", "ack", "fin", "rst", "psh", "urg", "ece", "cwr",
})
# Shared VLAN builder fields: the outer tag (vlan_id/vlan_priority)
# plus the optional inner tag (inner_vlan_id/inner_vlan_priority) that
# produces a double-tagged QinQ frame for the outer-only-parse tests.
# Every builder accepts these and inserts a 4-byte 802.1Q tag after
# the source MAC (FWL_V04_SPEC.md "Builder additions").
_VLAN_BUILDER_FIELDS = frozenset({
  "vlan_id", "vlan_priority", "inner_vlan_id", "inner_vlan_priority",
})
_BUILDER_FIELD_TABLE: dict[str, frozenset[str]] = {
  "tcp": _TCP_BUILDER_FIELDS | _VLAN_BUILDER_FIELDS,
  "udp": frozenset({"src_ip", "dst_ip", "src_port",
                    "dst_port"}) | _VLAN_BUILDER_FIELDS,
  "icmp": frozenset({"src_ip", "dst_ip", "type",
                     "code"}) | _VLAN_BUILDER_FIELDS,
  # v0.2 IPv6 builders. Per PKT_V02_SPEC.md, the field names src_ip
  # and dst_ip are reused for symmetry with the v4 builders; the
  # values are RFC 4291 IPv6 strings, so the type is unambiguous to
  # the loader. src_ip6 and dst_ip6 are NOT separate fields on the v6
  # builders.
  "tcp6": _TCP_BUILDER_FIELDS | _VLAN_BUILDER_FIELDS,
  "udp6": frozenset({"src_ip", "dst_ip", "src_port",
                     "dst_port"}) | _VLAN_BUILDER_FIELDS,
  "icmp6": frozenset({"src_ip", "dst_ip", "type",
                      "code"}) | _VLAN_BUILDER_FIELDS,
}

# TCP flag bit positions in the flags byte (TCP header offset 13).
_TCP_FLAG_BITS = (
  ("fin", 0x01),
  ("syn", 0x02),
  ("rst", 0x04),
  ("psh", 0x08),
  ("ack", 0x10),
  ("urg", 0x20),
  ("ece", 0x40),
  ("cwr", 0x80),
)


def _tcp_flags_byte(fields: dict[str, Any]) -> int:
  """Assemble the TCP flags byte from the builder's bool fields."""
  flags = 0
  for name, bit in _TCP_FLAG_BITS:
    if fields.get(name, False):
      flags |= bit
  return flags


def _set_tcp_flag_decoded(decoded: dict[str, Any], fields: dict[str, Any]):
  """Default every TCP flag to False on the decoded-fields dict."""
  for name, _bit in _TCP_FLAG_BITS:
    decoded.setdefault(name, bool(fields.get(name, False)))


def parse_builder(text: str) -> dict[str, Any]:
  """Parse a builder expression into a dict of decoded fields.

  Returns a dict containing at least `proto`. Other keys depend on
  the builder used; per PKT_V01_SPEC.md:253, names not in the
  proto's field table are rejected at load time.
  """
  match = _BUILDER_RE.match(text)
  if not match:
    raise ValueError(f"unrecognized builder expression: {text!r}")
  proto = match.group("proto")
  allowed = _BUILDER_FIELD_TABLE[proto]
  fields: dict[str, Any] = {"proto": proto}
  for name, raw_value in _split_args(match.group("args")):
    if name not in allowed:
      raise ValueError(f"unknown {proto} field {name!r}")
    fields[name] = _parse_value(raw_value)
  return fields


_DEFAULT_SRC_MAC = b"\x02\x00\x00\x00\x00\x01"
_DEFAULT_DST_MAC = b"\x02\x00\x00\x00\x00\x02"
_ETH_P_IP = 0x0800
_ETH_P_IPV6 = 0x86DD
_ETH_P_8021Q = 0x8100
_IPPROTO_TCP = 6
_IPPROTO_UDP = 17
_IPPROTO_ICMP = 1
_IPPROTO_ICMPV6 = 58
_DEFAULT_V6_SRC = "2001:db8::1"
_DEFAULT_V6_DST = "2001:db8::2"


def _vlan_tci(vlan_id: int, vlan_priority: int) -> int:
  """Pack a 16-bit 802.1Q TCI: PCP(3) | DEI(1)=0 | VID(12)."""
  return ((vlan_priority & 0x7) << 13) | (vlan_id & 0x0FFF)


def _validated_vlan(vlan_id: Any, vlan_priority: Any) -> tuple[int, int]:
  """Resolve + range-check a (vid, pcp) pair, defaulting absent to 0."""
  vid = 0 if vlan_id is None else int(vlan_id)
  pcp = 0 if vlan_priority is None else int(vlan_priority)
  if not (0 <= vid <= 4095):
    raise ValueError(f"vlan_id out of range 0..4095: {vid}")
  if not (0 <= pcp <= 7):
    raise ValueError(f"vlan_priority out of range 0..7: {pcp}")
  return vid, pcp


def _eth_header(
  ether_type: int,
  vlan_id: Any,
  vlan_priority: Any,
  inner_vlan_id: Any = None,
  inner_vlan_priority: Any = None,
) -> tuple[bytes, dict[str, int], bool]:
  """Build the Ethernet header, inserting 802.1Q tag(s) if requested.

  Returns (header_bytes, vlan_decoded, is_qinq). When either vlan_id
  or vlan_priority is supplied, a 4-byte tag (TPID 0x8100 + TCI) is
  inserted after the source MAC and `vlan_decoded` carries the
  outer vlan_id/vlan_priority keys; otherwise the tag is absent and
  `vlan_decoded` is empty (an untagged frame, unchanged from
  pre-v0.4). When an inner tag is also supplied (QinQ), a second
  0x8100 tag follows the outer one and `is_qinq` is True — v0.4
  parses the outer tag only, so the caller drops the (now
  unreachable) L3/L4 decoded fields. `ether_type` is always the real
  L3 type (0x0800/0x86DD) and follows the tag stack.
  """
  has_outer = vlan_id is not None or vlan_priority is not None
  has_inner = inner_vlan_id is not None or inner_vlan_priority is not None
  header = _DEFAULT_DST_MAC + _DEFAULT_SRC_MAC
  vlan_decoded: dict[str, int] = {}
  if has_outer or has_inner:
    vid, pcp = _validated_vlan(vlan_id, vlan_priority)
    header += struct.pack(">HH", _ETH_P_8021Q, _vlan_tci(vid, pcp))
    vlan_decoded = {"vlan_id": vid, "vlan_priority": pcp}
    if has_inner:
      ivid, ipcp = _validated_vlan(inner_vlan_id, inner_vlan_priority)
      header += struct.pack(">HH", _ETH_P_8021Q, _vlan_tci(ivid, ipcp))
  header += struct.pack(">H", ether_type)
  return header, vlan_decoded, has_inner


def _ipv4_to_bytes(addr: Any, field: str = "ip") -> bytes:
  """Pack a dotted-quad IPv4 string as 4 big-endian bytes.

  Raises ValueError with the offending field name when `addr` isn't
  a dotted-quad string. Without this, an int passed for `src_ip`
  (e.g. `tcp(src_ip=16909060)`) crashes with an opaque AttributeError
  deep in the builder — surfaced by the explore-mode bug hunter.
  """
  if not isinstance(addr, str):
    raise ValueError(
      f"{field}: expected dotted-quad string, got "
      f"{type(addr).__name__} ({addr!r})"
    )
  parts = addr.split(".")
  if len(parts) != 4:
    raise ValueError(f"{field}: not an IPv4 dotted quad: {addr!r}")
  try:
    octets = [int(p) for p in parts]
  except ValueError:
    raise ValueError(f"{field}: not an IPv4 dotted quad: {addr!r}")
  for octet in octets:
    if not (0 <= octet <= 255):
      raise ValueError(f"{field}: IPv4 octet out of range 0..255: {octet}")
  return bytes(octets)


def _ipv4_checksum(header: bytes) -> int:
  """One's-complement sum over the IPv4 header words."""
  total = 0
  for i in range(0, len(header), 2):
    total += (header[i] << 8) | header[i + 1]
  while total >> 16:
    total = (total & 0xFFFF) + (total >> 16)
  return (~total) & 0xFFFF


def _l4_checksum(src4: bytes, dst4: bytes, proto_num: int,
                 l4: bytes) -> int:
  """TCP/UDP checksum over the IPv4 pseudo-header + L4 segment.

  Built frames carry a *valid* L4 checksum so a NAT rewrite (which
  updates it incrementally) can be checked on the wire — the BPF
  oracle recomputes it after every translation."""
  data = (src4 + dst4 + bytes([0, proto_num])
          + len(l4).to_bytes(2, "big") + l4)
  if len(data) % 2:
    data += b"\x00"
  total = 0
  for i in range(0, len(data), 2):
    total += (data[i] << 8) | data[i + 1]
  while total >> 16:
    total = (total & 0xFFFF) + (total >> 16)
  return (~total) & 0xFFFF


def _ipv6_to_bytes(addr: Any, field: str = "ip") -> bytes:
  """Pack an RFC 5952 canonical IPv6 string as 16 big-endian bytes (v0.2).

  Per PKT_V02_SPEC.md, builder field values must be RFC 5952
  canonical — the same discipline parser._parse_ipv6 enforces on
  .fw source literals. Without this gate, corpus authors can write
  tests whose source strings the .fw program can't contain.
  """
  import ipaddress as _ipaddress
  if not isinstance(addr, str):
    raise ValueError(
      f"{field}: expected IPv6 string, got "
      f"{type(addr).__name__} ({addr!r})"
    )
  try:
    parsed = _ipaddress.IPv6Address(addr)
  except _ipaddress.AddressValueError as e:
    raise ValueError(
      f"{field}: not a valid IPv6 address: {addr!r}"
    ) from e
  expected = _canonical_ipv6_for_builder(addr, parsed)
  if addr != expected:
    raise ValueError(
      f"builder {field}: {addr!r} must be RFC 5952 canonical IPv6 "
      f"(expected {expected!r})"
    )
  return parsed.packed


_IPV4_MAPPED_BLOCK_BUILDER = None


def _canonical_ipv6_for_builder(text, addr) -> str:
  """RFC 5952 canonical form for a builder field — mirrors parser.

  Rules 1-3 via IPv6Address.compressed; rule 4 (RFC 5952 §5)
  applies dotted-quad to the ::ffff:0:0/96 IPv4-mapped block. The
  parser holds an identical helper; lifting them into a shared
  module is a follow-up.
  """
  import ipaddress as _ipaddress
  global _IPV4_MAPPED_BLOCK_BUILDER
  if _IPV4_MAPPED_BLOCK_BUILDER is None:
    _IPV4_MAPPED_BLOCK_BUILDER = _ipaddress.IPv6Network("::ffff:0:0/96")
  if addr in _IPV4_MAPPED_BLOCK_BUILDER:
    v4 = _ipaddress.IPv4Address(int(addr) & 0xFFFFFFFF)
    return f"::ffff:{v4}"
  return addr.compressed


def _build_v6_packet(fields: dict[str, Any]) -> Packet:
  """Build a Packet for an IPv6 builder (tcp6/udp6/icmp6) — v0.2.

  Produces an Ethernet frame with EtherType 0x86DD, an IPv6 fixed
  header (40 bytes: version=6, traffic class=0, flow label=0,
  payload length, next header, hop limit=64, src/dst addresses), and
  the L4 header. No extension headers; ICMPv6 is type 128 (Echo
  Request). The decoded-fields dict carries `src_ip6`/`dst_ip6` keys
  (not `src_ip`/`dst_ip`) so a v0.1-shaped rule reading `pkt.src_ip`
  finds the field absent and falls through, matching FWL_V02_SPEC.md's
  cross-family rule.

  Per PKT_V02_SPEC.md, the `proto` key in the decoded dict is the
  wire-level next_header value translated to a v0.1-style keyword
  string (`tcp` for next_header=6, `udp` for 17, `icmp6` for 58).
  Whether a v0.1-shaped program SEES this proto value is governed by
  the v6-surface-activation rule the interpreter applies separately.
  """
  proto = fields["proto"]
  src = fields.get("src_ip", _DEFAULT_V6_SRC)
  dst = fields.get("dst_ip", _DEFAULT_V6_DST)

  if proto == "tcp6":
    next_header = _IPPROTO_TCP
    proto_str = "tcp"
    src_port = fields.get("src_port", 12345)
    dst_port = fields.get("dst_port", 80)
    flags = _tcp_flags_byte(fields)
    data_offset_reserved = 0x50
    l4 = struct.pack(
      ">HHIIBBHHH",
      src_port, dst_port,
      0, 0,
      data_offset_reserved, flags,
      8192, 0, 0,
    )
    decoded = {
      "ether_type": _ETH_P_IPV6,
      "proto": proto_str,
      "src_ip6": src,
      "dst_ip6": dst,
      "src_port": src_port,
      "dst_port": dst_port,
    }
    _set_tcp_flag_decoded(decoded, fields)
  elif proto == "udp6":
    next_header = _IPPROTO_UDP
    proto_str = "udp"
    src_port = fields.get("src_port", 12345)
    dst_port = fields.get("dst_port", 53)
    udp_len = 8
    l4 = struct.pack(">HHHH", src_port, dst_port, udp_len, 0)
    decoded = {
      "ether_type": _ETH_P_IPV6,
      "proto": proto_str,
      "src_ip6": src,
      "dst_ip6": dst,
      "src_port": src_port,
      "dst_port": dst_port,
    }
  else:
    # icmp6
    next_header = _IPPROTO_ICMPV6
    proto_str = "icmp6"
    # type defaults to 128 (Echo Request); code defaults to 0.
    # checksum, id, seq are left zero for tests.
    icmp6_type = fields.get("type", 128)
    icmp6_code = fields.get("code", 0)
    l4 = struct.pack(">BBHHH", icmp6_type, icmp6_code, 0, 0, 0)
    decoded = {
      "ether_type": _ETH_P_IPV6,
      "proto": proto_str,
      "src_ip6": src,
      "dst_ip6": dst,
      "icmp6_type": icmp6_type,
      "icmp6_code": icmp6_code,
    }

  payload_len = len(l4)
  # IPv6 fixed header: 4 bytes version+TC+flow, 2 bytes payload length,
  # 1 byte next header, 1 byte hop limit, 16 bytes src, 16 bytes dst.
  ipv6_header = (
    struct.pack(">IHBB", 0x60000000, payload_len, next_header, 64)
    + _ipv6_to_bytes(src, "src_ip")
    + _ipv6_to_bytes(dst, "dst_ip")
  )
  eth, vlan_decoded, is_qinq = _eth_header(
    _ETH_P_IPV6, fields.get("vlan_id"), fields.get("vlan_priority"),
    fields.get("inner_vlan_id"), fields.get("inner_vlan_priority"),
  )
  decoded = vlan_decoded if is_qinq else {**decoded, **vlan_decoded}
  raw = eth + ipv6_header + l4
  return Packet(raw=raw, fields=decoded)


def build_packet(fields: dict[str, Any]) -> Packet:
  """Build a Packet from a decoded-fields dict.

  Sensible defaults are filled in for missing fields so corpus
  authors only specify what matters for their test:

    src_ip = "1.1.1.1", dst_ip = "2.2.2.2"     (v4 builders)
    src_ip = "2001:db8::1", dst_ip = "::2"     (v6 builders)
    src_port = 12345, dst_port = 80            (TCP/UDP only)
    syn = false, ack = false                   (TCP only)

  v0.2 v6 builders (tcp6/udp6/icmp6) are dispatched to a separate
  helper because the IPv6 frame layout (40-byte fixed header,
  EtherType 0x86DD, 16-byte addresses, no checksum) differs from v4.
  """
  proto = fields["proto"]
  if proto in ("tcp6", "udp6", "icmp6"):
    return _build_v6_packet(fields)
  src_ip = fields.get("src_ip", "1.1.1.1")
  dst_ip = fields.get("dst_ip", "2.2.2.2")

  if proto == "tcp":
    proto_num = _IPPROTO_TCP
    src_port = fields.get("src_port", 12345)
    dst_port = fields.get("dst_port", 80)
    flags = _tcp_flags_byte(fields)
    # data offset = 5 (no options), reserved = 0
    data_offset_reserved = 0x50
    l4 = struct.pack(
      ">HHIIBBHHH",
      src_port, dst_port,
      0,                         # seq
      0,                         # ack_seq
      data_offset_reserved,
      flags,
      8192,                      # window
      0,                         # checksum (left zero for tests)
      0,                         # urgent
    )
    decoded = dict(fields)
    decoded.setdefault("src_ip", src_ip)
    decoded.setdefault("dst_ip", dst_ip)
    decoded.setdefault("src_port", src_port)
    decoded.setdefault("dst_port", dst_port)
    _set_tcp_flag_decoded(decoded, fields)
  elif proto == "udp":
    proto_num = _IPPROTO_UDP
    src_port = fields.get("src_port", 12345)
    dst_port = fields.get("dst_port", 53)
    udp_len = 8
    l4 = struct.pack(
      ">HHHH", src_port, dst_port, udp_len, 0
    )
    decoded = dict(fields)
    decoded.setdefault("src_ip", src_ip)
    decoded.setdefault("dst_ip", dst_ip)
    decoded.setdefault("src_port", src_port)
    decoded.setdefault("dst_port", dst_port)
  elif proto == "icmp":
    proto_num = _IPPROTO_ICMP
    # type defaults to 8 (echo request); code defaults to 0. checksum,
    # id, seq are left zero for tests.
    icmp_type = fields.get("type", 8)
    icmp_code = fields.get("code", 0)
    l4 = struct.pack(">BBHHH", icmp_type, icmp_code, 0, 0, 0)
    decoded = dict(fields)
    decoded.pop("type", None)
    decoded.pop("code", None)
    decoded.setdefault("src_ip", src_ip)
    decoded.setdefault("dst_ip", dst_ip)
    decoded["icmp_type"] = icmp_type
    decoded["icmp_code"] = icmp_code
  else:
    raise ValueError(f"unknown proto: {proto!r}")

  total_len = 20 + len(l4)
  ip_header = struct.pack(
    ">BBHHHBBH4s4s",
    0x45,                         # version=4, IHL=5
    0,                            # DSCP/ECN
    total_len,
    0,                            # id
    0,                            # flags + frag offset
    64,                           # TTL
    proto_num,
    0,                            # checksum placeholder
    _ipv4_to_bytes(src_ip, "src_ip"),
    _ipv4_to_bytes(dst_ip, "dst_ip"),
  )
  checksum = _ipv4_checksum(ip_header)
  ip_header = ip_header[:10] + struct.pack(">H", checksum) + ip_header[12:]

  # Fill a valid TCP/UDP checksum (ICMP keeps its zero placeholder —
  # v0.4 NAT never rewrites ICMP, so no oracle checks it). The L4
  # checksum field sits at offset 16 (TCP) / 6 (UDP).
  src4 = _ipv4_to_bytes(src_ip, "src_ip")
  dst4 = _ipv4_to_bytes(dst_ip, "dst_ip")
  if proto == "tcp":
    c = _l4_checksum(src4, dst4, proto_num, l4)
    l4 = l4[:16] + struct.pack(">H", c) + l4[18:]
  elif proto == "udp":
    c = _l4_checksum(src4, dst4, proto_num, l4) or 0xFFFF
    l4 = l4[:6] + struct.pack(">H", c) + l4[8:]

  eth, vlan_decoded, is_qinq = _eth_header(
    _ETH_P_IP, fields.get("vlan_id"), fields.get("vlan_priority"),
    fields.get("inner_vlan_id"), fields.get("inner_vlan_priority"),
  )
  # v0.4 parses the outer tag only: behind a second tag the L3/L4
  # headers are unreachable, so the decoded dict exposes just the
  # outer VLAN fields (mirrors the emitter leaving v4_ok/l4_ok at 0).
  decoded = vlan_decoded if is_qinq else {**decoded, **vlan_decoded}
  raw = eth + ip_header + l4
  return Packet(raw=raw, fields=decoded)


